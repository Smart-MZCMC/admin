/**
 * 「这次失败是不是意味着登录态没了」的判定。
 *
 * 为什么要单独抽出来：这条规则决定了失败之后是**弹一句提示**还是**把人踢回登录页**，
 * 而它错判的代价是双向的——
 *   - 该踢的没踢：登录态已经失效，界面停在半登录状态，每个请求都 401，
 *     用户看到的是「按钮全在、点了全报错」，还会以为系统出了 bug；
 *   - 不该踢的踢了：一次普通的 400/409/500 就把管理员请去重新登录。
 *     权限编辑页正好把这件事放大到不可接受——后端对「你选的角色不存在」回的是
 *     400 unknown_role，那是一次**业务错误**，界面要显示「刷新页面后再试」并把
 *     草稿丢掉；踢去登录页的话这句话永远显示不出来，用户刷一百次登录也刷不出来。
 *
 * 因此判定只有一个来源：**HTTP 401**。后端 app/http/middleware 里所有「未登录 /
 * 令牌无效 / 用户已删除 / 令牌版本过期」都是 401，「权限不足 / 角色门槛不够」
 * 一律是 403（见 middleware/jwt.go 与 middleware/permission.go）。
 *
 * ⚠️ 不要写成「除 403 外一律结束会话」。403 是当前用户的真实权限状态，不是会话
 *    状态；而 400 / 404 / 409 / 500 / 502 / 503 全都是「请求或服务端的问题」，
 *    把它们当成会话失效就是误伤。
 *
 * 抽成纯函数（不碰 store、不碰 goto）是为了能单测：组件里的局部判断没法单测，
 * 而这条规则的每一档都必须有断言钉住——它一旦漂移，表现是「用户莫名其妙被登出」。
 */

/**
 * 这些接口的 4xx/5xx 都不是「会话过期」，不能触发统一登出。
 *
 * 登录与注册本身会返回 401/403；初始化向导在系统还没有任何账号时被调用，
 * 参数错误（400）、已初始化（403）、或初始化模式下的 503 都要原样展示给用户
 * ——之前的实现会把它们当成令牌失效，直接把人踢回登录页，向导页刚填的内容
 * 一整屏就没了。
 */
export const NO_SESSION_PATHS = new Set([
	'/api/auth/login',
	'/api/auth/admin-login',
	'/api/auth/register',
	'/api/setup/status',
	'/api/setup/apply'
]);

/**
 * 这个状态码是否意味着「令牌没了/过期了」。
 *
 * 只有 401 是。反过来断言「403 不算」也不够——必须同时把 400/409/5xx 排除掉，
 * 而逐一列举排除项迟早漏一个，所以这里走白名单。
 */
export function isSessionLost(status: number): boolean {
	return status === 401;
}

/** 这次失败要不要结束会话、清令牌并跳登录页。 */
export function shouldEndSession(path: string, status: number): boolean {
	return isSessionLost(status) && !NO_SESSION_PATHS.has(path);
}
